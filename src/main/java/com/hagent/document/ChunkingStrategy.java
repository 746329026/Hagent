package com.hagent.document;

/**
 * 文本切分策略 —— 由 {@link DocumentKind} 决定用哪一种。
 *
 * <p>策略是"行为"、种类是"文档种类"，分开是因为不同种类可能共用同一种策略
 * （{@code POLICY} / {@code FAQ} / {@code PRODUCT_DOC} 都按标题切）；实现在 {@code chunking} 包，
 * 一种策略一个实现。
 *
 * <p><b>硬约束：所有策略都要保证块 ≤ 上限。</b>embedding 有约 1000 汉字的输入上限，
 * 超出部分被<b>静默截断</b>（不报错、返回正常维度的向量），被截掉的后半部分对检索完全不可见。
 * 所以各策略都在"按语义边界切"与"不超限"之间折中：<b>语义边界优先，超限时强制再切</b>
 * （见 {@link ChunkingSupport}）。
 */
public enum ChunkingStrategy {

    /**
     * 整篇作为一块 —— 用于短且信息整体性的文档（如公司介绍）。
     *
     * <p>前置条件：文档必须短于块大小上限。超长时实现会<b>自动降级</b>为按段落聚合切分，
     * 而不是把超长文本硬塞进一个块（后半部分会被 embedding 静默截断）。
     */
    WHOLE_DOCUMENT,

    /**
     * 按 Markdown 标题切分 —— 每个标题及其正文成为一块。
     *
     * <p>标题是<b>作者主动标注的语义边界</b>，比按字数硬切准确，且天然产出可用于出处的"章节名"。
     * 没有标题时自动降级为按段落聚合（见 {@link #BY_PARAGRAPH}）。
     */
    BY_HEADING,

    /**
     * 按段落聚合切分 —— 把相邻段落合并成接近块大小的块。
     *
     * <p>段落是语义自然的边界（作者换段就是在换意思），比句子大、比整篇小：
     * 既能容纳完整意思，又不会大到稀释向量。整篇无换行时降级为按句子边界滑动切分。
     */
    BY_PARAGRAPH;

    /**
     * 这个策略在"按语义边界切"之后，<b>是否还需要</b>做大小约束。
     *
     * <p>用它表达"哪些策略必须额外防截断"，避免每个实现各自判断（目前三种都需要）。
     */
    public boolean needsSizeGuard() {
        return true;
    }
}
