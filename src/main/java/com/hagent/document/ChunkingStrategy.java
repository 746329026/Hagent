package com.hagent.document;

/**
 * 文本切分策略 —— 由 {@link DocumentKind} 决定用哪一种。
 *
 * <h2>为什么策略本身也要是一个枚举</h2>
 *
 * <p>策略是"<b>行为</b>"，而 {@link DocumentKind} 是"<b>文档种类</b>"。
 * 两者分开的理由是：<b>不同种类可能共用同一种策略</b>
 * （{@code POLICY} / {@code FAQ} / {@code PRODUCT_DOC} 都用"按标题切"）。
 * 若把策略直接写成各 {@code DocumentKind} 自己的实现方法，
 * 共同逻辑会被复制多份 —— 而"多个实现各抄一份"正是本项目
 * 在 {@code MessageCodec} / {@code MemoryTrimmer} 上明确避免过的做法。
 *
 * <p>所以这里保持"种类 → 策略"的映射（在 {@link DocumentKind} 里声明），
 * 而策略的具体实现放在 {@code chunking} 包，<b>每种策略只有一个实现</b>。
 *
 * <h2>★ 一个必须遵守的硬约束：所有策略都要保证块 ≤ 上限</h2>
 *
 * <p>本项目的 embedding 模型（本地 Ollama {@code mxbai-embed-large}）有约
 * <b>1000 个汉字</b>的输入上限，超出部分会被<b>静默截断</b>（实测：不报错、返回正常维度的向量）。
 * 一旦被截断，块的<b>后半部分对检索完全不可见</b>，而系统没有任何异常迹象。
 *
 * <p>因此 {@link #BY_HEADING} 与 {@link #BY_PARAGRAPH} 都必须在
 * "按语义边界切"与"不超过上限"之间做折中：<b>语义边界优先，但超限时强制再切</b>。
 * 详见 {@link #WHOLE_DOCUMENT} 的说明。
 */
public enum ChunkingStrategy {

    /**
     * 整篇作为一块 —— 用于短且信息整体性的文档（如公司介绍）。
     *
     * <p><b>★ 这个策略有前置条件</b>：文档必须短于块大小上限。若文档超长，
     * 实现会<b>自动降级</b>为按段落聚合切分，而不是把超长文本硬塞进一个块
     * （那样后半部分会被 embedding 静默截断）。
     */
    WHOLE_DOCUMENT,

    /**
     * 按 Markdown 标题切分 —— 每个标题及其正文成为一块。
     *
     * <p><b>为什么标题是好的切分点</b>：它是<b>作者主动标注的语义边界</b>。
     * 作者写"## 假期管理"就是在说"从这里开始讲另一件事"。
     * 这比按字数硬切准确得多，而且天然产出了可以用于出处的"章节名"。
     *
     * <p>没有标题时自动降级为按段落聚合（见 {@link #BY_PARAGRAPH}）。
     */
    BY_HEADING,

    /**
     * 按段落聚合切分 —— 把相邻段落合并成接近块大小的块。
     *
     * <p><b>为什么以段落为单位</b>：一大块没有标题的文本通常仍有段落（换行）。
     * 段落是语义自然的边界（作者换段就是在换意思），且比句子大、比整篇小 ——
     * 既能容纳完整意思，又不会大到稀释向量。
     *
     * <p>连段落都没有（整篇无换行）时降级为按句子边界滑动切分。
     */
    BY_PARAGRAPH;

    /**
     * 这个策略在"按语义边界切"之后，<b>是否还需要</b>做大小约束。
     *
     * <p>用它来表达"哪些策略必须额外防截断"，避免每个实现各自判断。
     * 目前三种策略都需要 —— 但把它显式写出来，是为了在将来出现
     * "天然不会超限"的策略（如 FAQ 的一问一答）时有个明确的位置说明原因。
     */
    public boolean needsSizeGuard() {
        return true;
    }
}
