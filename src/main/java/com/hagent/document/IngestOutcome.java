package com.hagent.document;

/**
 * 一份文档入库后的<b>处理结论</b>。
 *
 * <h2>★ 为什么必须区分"跳过"与"写入"，而不是只报一个数字</h2>
 *
 * <p>如果入库只返回"处理了 N 篇"，那么下面两种情况会看起来完全一样：
 * <pre>
 *   ① 真的写入了 1 篇新文档        → 期望的结果
 *   ② 哈希没变、跳过了 1 篇        → 也期望，但含义完全不同
 * </pre>
 * 而这正是排查时最先要分清的事：<b>"同步没生效"与"同步正确地判定为无需变更"</b>
 * 是两件相反的事情。把它们混成一个计数，等于把"幂等生效了"和"什么都没做"
 * 变成同一个信号 —— 于是无法从日志判断系统是否正常。
 *
 * <p>这与本项目在多个地方坚持的做法一致：<b>让"发生了什么"可区分</b>，
 * 而不是把不同含义的结果压成一个计数。
 *
 * <p><b>为什么没有 {@code FAILED}</b>：单份文档处理失败时本服务直接抛异常，
 * 由调用方决定是"整批中止"还是"跳过这一份继续"。
 * 失败<b>不是</b>一种"正常的处理结论"，把它塞进枚举会让调用方
 * 容易把失败当成可忽略的返回值（"反正有 FAILED 这个分支"）。
 */
public enum IngestOutcome {

    /** 库中不存在该来源 → 全量写入。 */
    ADDED,

    /** 库中存在该来源、且文档哈希已变 → 删除旧块后写入新块。 */
    UPDATED,

    /**
     * 库中存在该来源、且文档哈希未变 → <b>跳过</b>，不做任何切分与 embedding。
     *
     * <p>这是幂等的正常路径，不是异常情况。它省下的是"整篇重新切分 +
     * 每块一次 embedding + 每块一次写入"的全部成本。
     */
    SKIPPED_UNCHANGED;

    /**
     * 本次是否<b>没有</b>被跳过（只说明"我们处理过它"，<b>不代表写入了任何东西</b>）。
     *
     * <p>★ 阶段 12 改名：原名 {@code written()}，但它对"正文为空 → ADDED、0 块"的文档
     * 也返回 {@code true} —— 那是<b>契约说谎</b>（协议第 12 条规则 4）。
     * "是否真的写入了块"看 {@code IngestResult#written()}（{@code chunkCount > 0}）。
     */
    public boolean notSkipped() {
        return this != SKIPPED_UNCHANGED;
    }
}
