package com.hagent.app;

/**
 * 工具向外<b>同步发出事件</b>的通道。
 *
 * <h2>★ 为什么需要它，而不是让工具返回值里带事件</h2>
 *
 * <p>工具的返回值是<b>给模型看的字符串</b>（模型只能读文本）——
 * 而"本次参考了哪几篇文档"是<b>给前端看的结构化数据</b>。
 * 把结构化数据塞进那段字符串再解析回来，是本项目明确反对的做法
 * （协议第 7 条：结构化数据走结构化通道，别让它经过文本再被解析）。
 *
 * <h2>★ 为什么是"同步"的回调，而不是 {@code Flux}</h2>
 *
 * <p>工具的执行路径是<b>阻塞</b>的：{@code ToolCallingManager.executeToolCalls}
 * 是普通同步方法，它内部反射调用工具方法并等结果。在那里面返回 {@code Flux}
 * 没有意义 —— 没人会在那个栈帧上订阅它。
 *
 * <p>所以这里定义成一个最简单的"发出即忘记"接口，
 * 由管线在工具执行期间把它接到自己的事件流上。
 *
 * <h2>★ 实现方必须保证线程安全与顺序</h2>
 *
 * <p>模型可能一次请求多个工具（{@code toolCalls} 是列表）。框架当前是顺序执行的
 * （实测 {@code DefaultToolCallingManager} 逐个调用），所以顺序与调用顺序一致 ——
 * 但实现方不应依赖"只会有一个线程"这个假设。
 */
@FunctionalInterface
public interface ToolEventSink {

    /**
     * 发出一个事件。
     *
     * <p><b>实现方不应抛出异常</b>：工具执行路径上抛出的异常会被框架转成
     * "工具失败"的文本，从而把一次正常的检索变成用户看到的失败。
     * 发出事件失败不该影响工具本身的成败。
     */
    void emit(PipelineEvent event);
}
